CREATE FUNCTION cobweb_join_default_group() RETURNS trigger LANGUAGE plpgsql AS $join_default$
DECLARE default_gid BIGINT; default_role_id BIGINT;
BEGIN
    SELECT g.id,r.id INTO default_gid,default_role_id FROM study_groups g
        JOIN group_roles r ON r.group_id=g.id AND r.builtin_key='MEMBER'
        WHERE g.system_key='COBWEB_DEFAULT' AND g.status='ACCEPTED';
    IF default_gid IS NULL OR default_role_id IS NULL THEN
        RAISE EXCEPTION 'COBWEB default group is unavailable' USING ERRCODE='23514';
    END IF;
    INSERT INTO group_members (user_id,group_id,member_number,permission,role_id) VALUES (NEW.id,default_gid,NEW.id,'MEMBER',default_role_id);
    RETURN NEW;
END;
