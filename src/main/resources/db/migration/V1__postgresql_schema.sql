-- CobWeb PostgreSQL 단일 초기 스키마: 기존 MySQL V1~V22의 최종 상태입니다.
-- 새 PostgreSQL DB에서만 실행합니다. 기존 DB/데이터/마이그레이션 이력을 덮어쓰지 않습니다.
-- 기존 MySQL은 별도 백업·변환·검증 후 이관해야 합니다. DB 생성/암호/운영 데이터는 포함하지 않습니다.
-- JSONB, JPA 호환 VARCHAR+CHECK, UTC TIMESTAMP(6), identity PK를 사용합니다.
-- lower() UNIQUE는 대소문자 중복만 방지하며 MySQL의 악센트 무시 collation과 완전히 같지 않습니다.

-- 1. 계정·감사·인증: 토큰 원문이 아닌 서버 계산 지문만 보관합니다.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(16) NOT NULL, email VARCHAR(255),
    provider VARCHAR(20) CHECK (provider IN ('GOOGLE','GITHUB','NAVER')), provider_id VARCHAR(255),
    password VARCHAR(255) NOT NULL, bio VARCHAR(300) NOT NULL DEFAULT '', github_url VARCHAR(255) NOT NULL DEFAULT '',
    role VARCHAR(20) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER','OPERATOR','DEVELOPER')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','TIMEOUT','STOPPED','BANNED')),
    solved_count INTEGER NOT NULL DEFAULT 0, submit_count INTEGER NOT NULL DEFAULT 0,
    rank_type VARCHAR(20) NOT NULL DEFAULT 'INITIATE'
        CHECK (rank_type IN ('INITIATE','SKILLED','ELITE','EXPERT','LEGEND','MYTHIC','ABSOLUTE')),
    rank_int INTEGER NOT NULL DEFAULT 5, login_failed_count INTEGER NOT NULL DEFAULT 0,
    access_token_version BIGINT NOT NULL DEFAULT 0, last_login_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_password_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT chk_users_provider_identity CHECK ((provider IS NULL AND provider_id IS NULL) OR (provider IS NOT NULL AND provider_id IS NOT NULL)),
    CONSTRAINT chk_users_counts CHECK (solved_count >= 0 AND submit_count >= 0),
    CONSTRAINT chk_users_rank_int CHECK (rank_int BETWEEN 1 AND 5),
    CONSTRAINT chk_users_login_failed_count CHECK (login_failed_count >= 0)
);
CREATE UNIQUE INDEX uk_users_username ON users (lower(username));
CREATE UNIQUE INDEX uk_users_email ON users (lower(email));
CREATE UNIQUE INDEX uk_users_provider_identity ON users (provider,lower(provider_id));
CREATE INDEX idx_users_ranking ON users (solved_count DESC,submit_count ASC);
CREATE INDEX idx_users_created_at ON users (created_at);
CREATE TABLE users_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    attempt_email VARCHAR(255), attempt_name VARCHAR(16),
    status VARCHAR(30) NOT NULL CHECK (status IN ('SUCCESS','FAIL_PASSWORD_MISMATCH','FAIL_USER_NOT_FOUND','BANNED_USER')),
    log_created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    client_ip VARCHAR(45) NOT NULL, user_agent VARCHAR(255)
);
CREATE INDEX idx_users_log_created_at ON users_log (log_created_at);
CREATE INDEX idx_users_log_client_ip_created_at ON users_log (client_ip,log_created_at);
CREATE INDEX idx_users_log_user_created_at ON users_log (user_id,log_created_at);
CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, token VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL, created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uk_refresh_token_user UNIQUE (user_id), CONSTRAINT uk_refresh_token_token UNIQUE (token)
);
CREATE INDEX idx_refresh_token_expires_at ON refresh_token (expires_at);
CREATE TABLE email_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(255) NOT NULL, code_hash VARCHAR(64) NOT NULL,
    purpose VARCHAR(20) NOT NULL DEFAULT 'JOIN' CHECK (purpose IN ('JOIN','PASSWORD_RESET')),
    is_verified BOOLEAN NOT NULL DEFAULT FALSE, expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX idx_email_verifications_lookup ON email_verifications (email,purpose,created_at DESC);
CREATE INDEX idx_email_verifications_expires_at ON email_verifications (expires_at);
CREATE TABLE password_reset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, reset_token VARCHAR(64) NOT NULL,
    is_used BOOLEAN NOT NULL DEFAULT FALSE, expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uk_password_reset_token UNIQUE (reset_token)
);
CREATE INDEX idx_password_reset_user_id ON password_reset (user_id);
CREATE INDEX idx_password_reset_expires_at ON password_reset (expires_at);
CREATE TABLE auth_rate_limits (
    limit_key CHAR(64) COLLATE "C" PRIMARY KEY, window_started_at TIMESTAMP(6) NOT NULL, attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_auth_rate_limits_started_at ON auth_rate_limits (window_started_at);
CREATE TABLE email_verification_guards (guard_key CHAR(64) COLLATE "C" PRIMARY KEY,touched_at TIMESTAMP(6) NOT NULL);
CREATE INDEX idx_email_verification_guards_touched_at ON email_verification_guards (touched_at);

-- 2. 그룹·역할·가입 원장
CREATE TABLE study_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, group_name VARCHAR(16) NOT NULL,
    group_description VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING','ACCEPTED','REJECTED')),
    system_key VARCHAR(32) COLLATE "C", created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uk_study_groups_system_key UNIQUE (system_key),
    CONSTRAINT chk_study_groups_system_key CHECK (system_key IS NULL OR system_key='COBWEB_DEFAULT')
);
CREATE UNIQUE INDEX uk_study_groups_name ON study_groups (lower(group_name));
CREATE INDEX idx_study_groups_status_created_at ON study_groups (status,created_at);
CREATE TABLE group_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES study_groups(id) ON DELETE CASCADE, role_name VARCHAR(32) NOT NULL, builtin_key VARCHAR(32),
    can_view_problems BOOLEAN NOT NULL DEFAULT FALSE, can_create_problems BOOLEAN NOT NULL DEFAULT FALSE,
    can_edit_problems BOOLEAN NOT NULL DEFAULT FALSE, can_review_problems BOOLEAN NOT NULL DEFAULT FALSE,
    can_manage_members BOOLEAN NOT NULL DEFAULT FALSE, can_manage_roles BOOLEAN NOT NULL DEFAULT FALSE,
    can_manage_group BOOLEAN NOT NULL DEFAULT FALSE, can_create_contests BOOLEAN NOT NULL DEFAULT FALSE,
    can_manage_contests BOOLEAN NOT NULL DEFAULT FALSE, can_view_contest_results BOOLEAN NOT NULL DEFAULT FALSE,
    can_take_contests BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uk_group_roles_group_id UNIQUE (group_id,id),
    CONSTRAINT chk_group_roles_owner_core CHECK (builtin_key <> 'OWNER' OR (can_manage_members AND can_manage_roles AND can_manage_group))
);
CREATE UNIQUE INDEX uk_group_roles_name ON group_roles (group_id,lower(role_name));
CREATE UNIQUE INDEX uk_group_roles_builtin ON group_roles (group_id,lower(builtin_key));
CREATE TABLE group_members (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES study_groups(id) ON DELETE CASCADE,
    member_number BIGINT NOT NULL DEFAULT 1,
    permission VARCHAR(20) NOT NULL DEFAULT 'MEMBER' CHECK (permission IN ('MEMBER','ADMIN','OWNER')),
    role_id BIGINT NOT NULL, joined_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    PRIMARY KEY (user_id,group_id), CONSTRAINT uk_group_members_number UNIQUE (group_id,member_number),
    CONSTRAINT chk_group_members_number CHECK (member_number > 0),
    CONSTRAINT fk_group_members_role FOREIGN KEY (group_id,role_id) REFERENCES group_roles(group_id,id) ON DELETE RESTRICT
);
CREATE INDEX idx_group_members_group_permission ON group_members (group_id,permission);
CREATE INDEX idx_group_members_role ON group_members (group_id,role_id);

-- 3. 문제·공개 예제·비공개 채점 자료: 제목은 일반 문제/그룹별 고유 범위로 관리합니다.
CREATE TABLE problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, problem_number INTEGER NOT NULL, problem_title VARCHAR(200) NOT NULL,
    rank_type VARCHAR(20) NOT NULL DEFAULT 'INITIATE'
        CHECK (rank_type IN ('INITIATE','SKILLED','ELITE','EXPERT','LEGEND','MYTHIC','ABSOLUTE')),
    rank_int INTEGER NOT NULL DEFAULT 1, description TEXT NOT NULL, input_description TEXT NOT NULL,
    output_description TEXT NOT NULL, constraints_text TEXT, time_limit_ms INTEGER NOT NULL DEFAULT 1000,
    memory_limit_mb INTEGER NOT NULL DEFAULT 256,
    judge_type VARCHAR(20) NOT NULL DEFAULT 'STANDARD' CHECK (judge_type IN ('STANDARD','SPECIAL','EFFICIENCY')),
    execution_mode VARCHAR(16) NOT NULL DEFAULT 'STDIN' CHECK (execution_mode IN ('STDIN','FUNCTION','SQL')),
    function_abi_compatible BOOLEAN NOT NULL DEFAULT FALSE, function_signature JSONB,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PENDING_REVIEW','PUBLISHED','REJECTED','ARCHIVED')),
    visibility VARCHAR(16) NOT NULL DEFAULT 'PRIVATE' CHECK (visibility IN ('PUBLIC','GROUP','PRIVATE')),
    requested_visibility VARCHAR(16) NOT NULL DEFAULT 'PUBLIC' CHECK (requested_visibility IN ('PUBLIC','GROUP','PRIVATE')),
    submission_count BIGINT NOT NULL DEFAULT 0, accepted_count BIGINT NOT NULL DEFAULT 0, like_count BIGINT NOT NULL DEFAULT 0,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT, author_public BOOLEAN NOT NULL DEFAULT FALSE,
    group_id BIGINT REFERENCES study_groups(id) ON DELETE RESTRICT,
    title_scope BIGINT GENERATED ALWAYS AS (COALESCE(group_id,0)) STORED,
    source_name VARCHAR(255), source_url VARCHAR(1000),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'), published_at TIMESTAMP(6),
    CONSTRAINT uk_problems_number UNIQUE (problem_number),
    CONSTRAINT chk_problems_rank_int CHECK (rank_int BETWEEN 1 AND 5),
    CONSTRAINT chk_problems_limits CHECK (time_limit_ms > 0 AND memory_limit_mb > 0),
    CONSTRAINT chk_problems_counts CHECK (submission_count >= 0 AND accepted_count >= 0 AND like_count >= 0 AND accepted_count <= submission_count),
    CONSTRAINT chk_problems_group_visibility CHECK ((visibility='GROUP' AND group_id IS NOT NULL) OR visibility IN ('PUBLIC','PRIVATE'))
);
CREATE UNIQUE INDEX uk_problems_title_scope ON problems (title_scope,lower(problem_title));
CREATE INDEX idx_problems_listing ON problems (status,visibility,problem_number);
CREATE INDEX idx_problems_rank ON problems (rank_type,rank_int);
CREATE INDEX idx_problems_group_listing ON problems (group_id,status,problem_number);
CREATE INDEX idx_problems_author_created_at ON problems (author_id,created_at);
CREATE TABLE problem_number_sequence (id INTEGER PRIMARY KEY,next_number INTEGER NOT NULL);
INSERT INTO problem_number_sequence (id,next_number) VALUES (1,1000);
CREATE TABLE problem_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PENDING_REVIEW','PUBLISHED','REJECTED','ARCHIVED')),
    cause TEXT, checker_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX idx_problem_status_history_problem_created_at ON problem_status_history (problem_id,created_at);
CREATE TABLE problem_examples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    input_text TEXT NOT NULL, output_text TEXT NOT NULL, explanation TEXT, display_order INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT uk_problem_examples_order UNIQUE (problem_id,display_order), CONSTRAINT chk_problem_examples_order CHECK (display_order > 0)
);
CREATE TABLE problem_test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    input_data TEXT NOT NULL, expected_output TEXT NOT NULL,
    compare_type VARCHAR(32) NOT NULL DEFAULT 'TRIM_TRAILING_WHITESPACE'
        CHECK (compare_type IN ('EXACT','TRIM_TRAILING_WHITESPACE','FLOAT_TOLERANCE','SPECIAL_CHECKER')),
    score INTEGER NOT NULL DEFAULT 0, display_order INTEGER NOT NULL DEFAULT 1, is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uk_problem_test_cases_order UNIQUE (problem_id,display_order),
    CONSTRAINT chk_problem_test_cases_score CHECK (score >= 0), CONSTRAINT chk_problem_test_cases_order CHECK (display_order > 0)
);
CREATE INDEX idx_problem_test_cases_judging ON problem_test_cases (problem_id,is_active,display_order);
CREATE TABLE tags (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(50) NOT NULL);
CREATE UNIQUE INDEX uk_tags_name ON tags (lower(name));
CREATE TABLE problem_tags (
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (problem_id,tag_id)
);
CREATE INDEX idx_problem_tags_tag_problem ON problem_tags (tag_id,problem_id);
CREATE TABLE problem_languages (
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,language VARCHAR(30) NOT NULL,PRIMARY KEY (problem_id,language)
);
CREATE TABLE problem_likes (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),PRIMARY KEY (user_id,problem_id)
);
CREATE INDEX idx_problem_likes_problem_created_at ON problem_likes (problem_id,created_at);
CREATE TABLE reference_solutions (
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,language VARCHAR(30) NOT NULL,
    file_name VARCHAR(120) NOT NULL,source_code TEXT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),PRIMARY KEY (problem_id,language)
);
CREATE TABLE problem_starter_codes (
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,language VARCHAR(32) NOT NULL,source_code TEXT NOT NULL,
    PRIMARY KEY (problem_id,language),CONSTRAINT chk_problem_starter_codes_bytes CHECK (OCTET_LENGTH(source_code) BETWEEN 1 AND 65536)
);

-- 4. 그룹 코테·제출·채점 lease 및 판정 재사용
CREATE TABLE group_contests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,group_id BIGINT NOT NULL REFERENCES study_groups(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,starts_at TIMESTAMP(6) NOT NULL,ends_at TIMESTAMP(6) NOT NULL,
    replay_allowed BOOLEAN NOT NULL DEFAULT FALSE,capture_protection BOOLEAN NOT NULL DEFAULT FALSE,
    window_switch_protection BOOLEAN NOT NULL DEFAULT FALSE,created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT chk_group_contests_window CHECK (starts_at < ends_at)
);
CREATE INDEX idx_group_contests_group_time ON group_contests (group_id,starts_at,id);
CREATE TABLE contest_problems (
    contest_id BIGINT NOT NULL REFERENCES group_contests(id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE RESTRICT,display_order INTEGER NOT NULL,
    PRIMARY KEY (contest_id,problem_id),CONSTRAINT uk_contest_problems_order UNIQUE (contest_id,display_order),
    CONSTRAINT chk_contest_problems_order CHECK (display_order > 0)
);
CREATE INDEX idx_contest_problems_problem ON contest_problems (problem_id,contest_id);
CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,language VARCHAR(30) NOT NULL,source_code TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','RUNNING','ACCEPTED','WRONG_ANSWER',
        'TIME_LIMIT_EXCEEDED','MEMORY_LIMIT_EXCEEDED','RUNTIME_ERROR','COMPILATION_ERROR','SYSTEM_ERROR')),
    score INTEGER NOT NULL DEFAULT 0,execution_time_ms INTEGER,memory_usage_kb INTEGER,
    submitted_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),judged_at TIMESTAMP(6),
    claimed_at TIMESTAMP(6),judge_token VARCHAR(36),judge_heartbeat_at TIMESTAMP(6),judge_attempts INTEGER NOT NULL DEFAULT 0,
    contest_id BIGINT REFERENCES group_contests(id) ON DELETE RESTRICT,
    source_sha256 CHAR(64) COLLATE "C",judge_context_sha256 CHAR(64) COLLATE "C",
    reused_from_submission_id BIGINT REFERENCES submissions(id) ON DELETE SET NULL,diagnostic_json JSONB,
    CONSTRAINT fk_submissions_contest_problem FOREIGN KEY (contest_id,problem_id) REFERENCES contest_problems(contest_id,problem_id) ON DELETE RESTRICT,
    CONSTRAINT chk_submissions_score CHECK (score >= 0),
    CONSTRAINT chk_submissions_execution_time CHECK (execution_time_ms IS NULL OR execution_time_ms >= 0),
    CONSTRAINT chk_submissions_memory_usage CHECK (memory_usage_kb IS NULL OR memory_usage_kb >= 0),
    CONSTRAINT chk_submissions_judge_attempts CHECK (judge_attempts >= 0),
    CONSTRAINT chk_submissions_source_bytes CHECK (OCTET_LENGTH(source_code) BETWEEN 1 AND 65536),
    CONSTRAINT chk_submission_diagnostic_size CHECK (diagnostic_json IS NULL OR OCTET_LENGTH(diagnostic_json::text) <= 8192)
);
CREATE INDEX idx_submissions_user_submitted_at ON submissions (user_id,submitted_at DESC);
CREATE INDEX idx_submissions_problem_submitted_at ON submissions (problem_id,submitted_at DESC);
CREATE INDEX idx_submissions_problem_user_status ON submissions (problem_id,user_id,status);
CREATE INDEX idx_submission_queue ON submissions (status,submitted_at,id);
CREATE INDEX idx_submission_lease ON submissions (status,judge_heartbeat_at,id);
CREATE INDEX idx_submissions_contest_problem ON submissions (contest_id,problem_id);
CREATE INDEX idx_submissions_contest_user ON submissions (contest_id,user_id,problem_id,submitted_at);
CREATE INDEX idx_submissions_judgement_reuse ON submissions (user_id,problem_id,language,contest_id,source_sha256,judge_context_sha256,id);
CREATE TABLE submission_test_case_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,submission_id BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
    test_case_id BIGINT REFERENCES problem_test_cases(id) ON DELETE SET NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('ACCEPTED','WRONG_ANSWER','TIME_LIMIT_EXCEEDED','MEMORY_LIMIT_EXCEEDED',
        'RUNTIME_ERROR','COMPILATION_ERROR','SYSTEM_ERROR')),
    score INTEGER NOT NULL DEFAULT 0,execution_time_ms INTEGER,memory_usage_kb INTEGER,
    CONSTRAINT chk_submission_test_case_results_score CHECK (score >= 0)
);
CREATE INDEX idx_submission_test_case_results_submission ON submission_test_case_results (submission_id);
CREATE TABLE user_solved_problems (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    solved_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),PRIMARY KEY (user_id,problem_id)
);
CREATE INDEX idx_user_solved_problems_problem_solved_at ON user_solved_problems (problem_id,solved_at);
CREATE TABLE contest_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,contest_id BIGINT NOT NULL REFERENCES group_contests(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,event_id CHAR(36) NOT NULL,
    event_type VARCHAR(32) NOT NULL CHECK (event_type IN ('WINDOW_BLUR','VISIBILITY_HIDDEN','FULLSCREEN_EXIT',
        'COPY_BLOCKED','PRINT_BLOCKED','CAPTURE_KEY')),occurred_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_contest_events_idempotency UNIQUE (contest_id,user_id,event_id)
);
CREATE INDEX idx_contest_events_rate ON contest_events (contest_id,user_id,occurred_at);

-- 5. 커뮤니티·댓글·수정/삭제 이력: 서비스의 논리 삭제 후에도 원문은 계속 보존합니다.
CREATE TABLE community_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(20) NOT NULL CHECK (category IN ('HARDWARE','SOFTWARE','NEWS','PROBLEM_QNA','MAJOR_QNA','GENERAL','NOTICE')),
    title VARCHAR(200) NOT NULL,body TEXT NOT NULL,problem_id BIGINT REFERENCES problems(id) ON DELETE SET NULL,
    author_id BIGINT REFERENCES users(id) ON DELETE SET NULL,author_username VARCHAR(255) NOT NULL,version BIGINT NOT NULL DEFAULT 1,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,deleted_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT chk_community_post_version CHECK (version >= 1),CONSTRAINT chk_community_post_body CHECK (CHAR_LENGTH(body) <= 20000)
);
CREATE INDEX idx_community_posts_listing ON community_posts (is_deleted,category,created_at DESC,id DESC);
CREATE INDEX idx_community_posts_author ON community_posts (author_id,created_at DESC);
CREATE TABLE community_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,post_id BIGINT NOT NULL REFERENCES community_posts(id) ON DELETE RESTRICT,
    parent_id BIGINT REFERENCES community_comments(id) ON DELETE RESTRICT,depth INTEGER NOT NULL DEFAULT 0,body TEXT NOT NULL,
    author_id BIGINT REFERENCES users(id) ON DELETE SET NULL,author_username VARCHAR(255) NOT NULL,version BIGINT NOT NULL DEFAULT 1,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,deleted_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT chk_community_comment_depth CHECK (depth BETWEEN 0 AND 2),
    CONSTRAINT chk_community_comment_version CHECK (version >= 1),CONSTRAINT chk_community_comment_body CHECK (CHAR_LENGTH(body) <= 5000)
);
CREATE INDEX idx_community_comments_post ON community_comments (post_id,id);
CREATE INDEX idx_community_comments_parent ON community_comments (parent_id);
CREATE TABLE community_post_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,post_id BIGINT NOT NULL REFERENCES community_posts(id) ON DELETE RESTRICT,
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATE','UPDATE','DELETE','RESTORE')),
    old_title VARCHAR(200),old_category VARCHAR(30),old_body TEXT,old_problem_id BIGINT,old_problem_number INTEGER,old_deleted BOOLEAN,old_version BIGINT,
    new_title VARCHAR(200) NOT NULL,new_category VARCHAR(30) NOT NULL,new_body TEXT NOT NULL,
    new_problem_id BIGINT,new_problem_number INTEGER,new_deleted BOOLEAN NOT NULL,new_version BIGINT NOT NULL,
    editor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,editor_username VARCHAR(255) NOT NULL,
    edited_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),reason VARCHAR(2000)
);
CREATE INDEX idx_community_post_revisions ON community_post_revisions (post_id,id DESC);
CREATE TABLE community_comment_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,comment_id BIGINT NOT NULL REFERENCES community_comments(id) ON DELETE RESTRICT,
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATE','UPDATE','DELETE','RESTORE')),
    old_body TEXT,old_deleted BOOLEAN,old_version BIGINT,new_body TEXT NOT NULL,new_deleted BOOLEAN NOT NULL,new_version BIGINT NOT NULL,
    editor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,editor_username VARCHAR(255) NOT NULL,
    edited_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),reason VARCHAR(2000)
