CREATE FUNCTION cobweb_preserve_system_group() RETURNS trigger LANGUAGE plpgsql AS $preserve_group$
BEGIN
    IF TG_OP='DELETE' THEN
        IF OLD.system_key IS NOT NULL THEN RAISE EXCEPTION 'System group cannot be deleted' USING ERRCODE='23514'; END IF;
        RETURN OLD;
    END IF;
    IF OLD.system_key IS DISTINCT FROM NEW.system_key OR
        (OLD.system_key IS NOT NULL AND (OLD.group_name IS DISTINCT FROM NEW.group_name OR OLD.status IS DISTINCT FROM NEW.status)) THEN
        RAISE EXCEPTION 'System group identity cannot be changed' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$preserve_group$;
