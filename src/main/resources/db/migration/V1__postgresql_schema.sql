CREATE TRIGGER study_groups_keep_system_group BEFORE DELETE ON study_groups FOR EACH ROW EXECUTE FUNCTION cobweb_preserve_system_group();

CREATE FUNCTION cobweb_preserve_system_membership() RETURNS trigger LANGUAGE plpgsql AS $preserve_member$
DECLARE system_membership BOOLEAN;
BEGIN
    IF TG_OP='DELETE' THEN
        -- 계정 삭제의 FK CASCADE와 공식 그룹 직접 탈퇴를 구분합니다.
        IF EXISTS (SELECT 1 FROM study_groups WHERE id=OLD.group_id AND system_key='COBWEB_DEFAULT')
            AND EXISTS (SELECT 1 FROM users WHERE id=OLD.user_id) THEN
            RAISE EXCEPTION 'System group membership cannot be removed' USING ERRCODE='23514';
        END IF;
        RETURN OLD;
    END IF;
    system_membership := EXISTS (SELECT 1 FROM study_groups WHERE id=NEW.group_id AND system_key='COBWEB_DEFAULT');
    IF TG_OP='UPDATE' THEN
        IF system_membership OR EXISTS (SELECT 1 FROM study_groups WHERE id=OLD.group_id AND system_key='COBWEB_DEFAULT') THEN
            IF OLD.user_id<>NEW.user_id OR OLD.group_id<>NEW.group_id OR OLD.member_number<>NEW.member_number THEN
                RAISE EXCEPTION 'System group membership identity cannot be changed' USING ERRCODE='23514';
            END IF;
            system_membership := TRUE;
        END IF;
    END IF;
    IF system_membership AND (NEW.permission='OWNER' OR EXISTS (
        SELECT 1 FROM group_roles WHERE group_id=NEW.group_id AND id=NEW.role_id AND builtin_key='OWNER')) THEN
        RAISE EXCEPTION 'System group cannot have a user owner' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$preserve_member$;
CREATE TRIGGER group_members_keep_system_membership BEFORE DELETE ON group_members FOR EACH ROW EXECUTE FUNCTION cobweb_preserve_system_membership();
CREATE TRIGGER group_members_no_system_owner_insert BEFORE INSERT ON group_members FOR EACH ROW EXECUTE FUNCTION cobweb_preserve_system_membership();
CREATE TRIGGER group_members_preserve_system_identity BEFORE UPDATE ON group_members FOR EACH ROW EXECUTE FUNCTION cobweb_preserve_system_membership();

