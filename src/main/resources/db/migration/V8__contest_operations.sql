-- 질문과 답변은 해당 시험 안에서만 읽습니다. 공지는 참가자의 질문 본문과 분리합니다.
CREATE TABLE contest_clarifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id BIGINT NOT NULL REFERENCES group_contests(id),
    problem_id BIGINT,
    asker_id BIGINT NOT NULL REFERENCES users(id),
    question TEXT NOT NULL CHECK (length(btrim(question)) BETWEEN 1 AND 2000),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    answer TEXT CHECK (length(btrim(answer)) BETWEEN 1 AND 2000),
    answered_by BIGINT REFERENCES users(id),
    answered_at TIMESTAMP(6),
    FOREIGN KEY (contest_id, problem_id) REFERENCES contest_problems(contest_id, problem_id),
    CHECK ((answer IS NULL) = (answered_at IS NULL) AND (answer IS NULL) = (answered_by IS NULL))
);
CREATE INDEX idx_contest_clarifications_staff ON contest_clarifications(contest_id,id DESC);
CREATE INDEX idx_contest_clarifications_mine ON contest_clarifications(contest_id,asker_id,id DESC);
CREATE TABLE contest_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id BIGINT NOT NULL REFERENCES group_contests(id),
    body TEXT NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
    author_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX idx_contest_announcements ON contest_announcements(contest_id,id DESC);

-- 복제본은 제출·순위·감시 이벤트를 공유하지 않습니다. 같은 그룹에 같은 출처의 문제를 중복 생성하지 않습니다.
ALTER TABLE group_contests
    ADD COLUMN copied_from_contest_id BIGINT REFERENCES group_contests(id),
    ADD COLUMN copy_request_id UUID,
    ADD CONSTRAINT contest_copy_request_pair CHECK ((copy_request_id IS NULL) = (copied_from_contest_id IS NULL));
CREATE UNIQUE INDEX uk_contest_copy_request ON group_contests(created_by,copy_request_id) WHERE copy_request_id IS NOT NULL;
ALTER TABLE problems ADD COLUMN copied_from_problem_id BIGINT REFERENCES problems(id);
CREATE UNIQUE INDEX uk_contest_group_problem_copy ON problems(group_id,copied_from_problem_id) WHERE copied_from_problem_id IS NOT NULL;
