CREATE TABLE community_posts (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    category ENUM('HARDWARE','SOFTWARE','NEWS','PROBLEM_QNA','MAJOR_QNA','GENERAL','NOTICE') NOT NULL,
    title VARCHAR(200) NOT NULL,
    body MEDIUMTEXT NOT NULL,
    problem_id BIGINT NULL,
    author_id BIGINT NULL,
    author_username VARCHAR(255) NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_community_post_problem FOREIGN KEY (problem_id) REFERENCES problems(id) ON DELETE SET NULL,
    CONSTRAINT fk_community_post_author FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_community_post_version CHECK (version>=1),
    CONSTRAINT chk_community_post_body CHECK (CHAR_LENGTH(body)<=20000),
    INDEX idx_community_posts_listing (is_deleted,category,created_at DESC,id DESC),
    INDEX idx_community_posts_author (author_id,created_at DESC)
);

CREATE TABLE community_comments (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    post_id BIGINT NOT NULL,
    parent_id BIGINT NULL,
    depth TINYINT NOT NULL DEFAULT 0,
    body TEXT NOT NULL,
    author_id BIGINT NULL,
    author_username VARCHAR(255) NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_community_comment_post FOREIGN KEY (post_id) REFERENCES community_posts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_comment_parent FOREIGN KEY (parent_id) REFERENCES community_comments(id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_comment_author FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_community_comment_depth CHECK (depth BETWEEN 0 AND 2),
    CONSTRAINT chk_community_comment_version CHECK (version>=1),
    CONSTRAINT chk_community_comment_body CHECK (CHAR_LENGTH(body)<=5000),
    INDEX idx_community_comments_post (post_id,id),
    INDEX idx_community_comments_parent (parent_id)
);

CREATE TABLE community_post_revisions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    post_id BIGINT NOT NULL,
    action ENUM('CREATE','UPDATE','DELETE','RESTORE') NOT NULL,
    old_title VARCHAR(200) NULL,
    old_category VARCHAR(30) NULL,
    old_body MEDIUMTEXT NULL,
    old_problem_id BIGINT NULL,
    old_problem_number INT NULL,
    old_deleted BOOLEAN NULL,
    old_version BIGINT NULL,
    new_title VARCHAR(200) NOT NULL,
    new_category VARCHAR(30) NOT NULL,
    new_body MEDIUMTEXT NOT NULL,
    new_problem_id BIGINT NULL,
    new_problem_number INT NULL,
    new_deleted BOOLEAN NOT NULL,
    new_version BIGINT NOT NULL,
    editor_id BIGINT NULL,
    editor_username VARCHAR(255) NOT NULL,
    edited_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    reason VARCHAR(2000) NULL,
    CONSTRAINT fk_community_post_revision_post FOREIGN KEY (post_id) REFERENCES community_posts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_post_revision_editor FOREIGN KEY (editor_id) REFERENCES users(id) ON DELETE SET NULL,
    INDEX idx_community_post_revisions (post_id,id DESC)
);

CREATE TABLE community_comment_revisions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    comment_id BIGINT NOT NULL,
    action ENUM('CREATE','UPDATE','DELETE','RESTORE') NOT NULL,
    old_body TEXT NULL,
    old_deleted BOOLEAN NULL,
    old_version BIGINT NULL,
    new_body TEXT NOT NULL,
    new_deleted BOOLEAN NOT NULL,
    new_version BIGINT NOT NULL,
    editor_id BIGINT NULL,
    editor_username VARCHAR(255) NOT NULL,
    edited_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    reason VARCHAR(2000) NULL,
    CONSTRAINT fk_community_comment_revision_comment FOREIGN KEY (comment_id) REFERENCES community_comments(id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_comment_revision_editor FOREIGN KEY (editor_id) REFERENCES users(id) ON DELETE SET NULL,
    INDEX idx_community_comment_revisions (comment_id,id DESC)
);
