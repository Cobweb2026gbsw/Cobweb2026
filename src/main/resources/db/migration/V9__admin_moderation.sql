-- 문제/제출 번호는 DB 외래키로 연결합니다. 시험 문의는 일반 접수함과 별개로 권한을 확인합니다.
CREATE TABLE problem_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    problem_id BIGINT NOT NULL REFERENCES problems(id),
    submission_id BIGINT REFERENCES submissions(id),
    contest_id BIGINT REFERENCES group_contests(id),
    category VARCHAR(20) NOT NULL CHECK (category IN ('PROBLEM_ERROR','JUDGING_APPEAL')),
    body TEXT NOT NULL CHECK (length(trim(body)) BETWEEN 1 AND 2000),
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED')),
    assignee_id BIGINT REFERENCES users(id),
    response TEXT NOT NULL DEFAULT '' CHECK (length(response)<=2000),
    updated_by BIGINT REFERENCES users(id),
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK ((category='JUDGING_APPEAL')=(submission_id IS NOT NULL)),
    CHECK (status<>'RESOLVED' OR length(trim(response))>0)
);
CREATE INDEX idx_issues_reporter ON problem_issues(reporter_id,contest_id,id DESC);
CREATE INDEX idx_issues_queue ON problem_issues(contest_id,status,id DESC);

-- 제한 만료는 쓰기 요청마다 DB 서버 시각으로 판정합니다. 해제해도 사유/기록은 보존합니다.
CREATE TABLE community_restrictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    feature VARCHAR(16) NOT NULL CHECK (feature IN ('POST','COMMENT')),
    reason TEXT NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 500),
    issued_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    revoked_by BIGINT REFERENCES users(id),
    CHECK (expires_at>created_at),
    CHECK ((revoked_at IS NULL)=(revoked_by IS NULL))
);
CREATE INDEX idx_community_restrictions_active ON community_restrictions(user_id,feature,expires_at) WHERE revoked_at IS NULL;

-- 검수 뒤 변경된 내용을 자동 공개하지 않도록 문제 편집/상태 전환의 판본을 저장합니다.
ALTER TABLE problems ADD COLUMN publication_revision BIGINT NOT NULL DEFAULT 0;
CREATE TABLE problem_release_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheduled_for TIMESTAMPTZ NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PUBLISHED','CANCELLED','FAILED')),
    finished_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id),
    failure_reason TEXT
);
CREATE INDEX idx_problem_releases_due ON problem_release_batches(scheduled_for,id) WHERE status='PENDING';
CREATE TABLE problem_release_items (
    batch_id BIGINT NOT NULL REFERENCES problem_release_batches(id),
    problem_id BIGINT NOT NULL REFERENCES problems(id),
    publication_revision BIGINT NOT NULL,
    PRIMARY KEY(batch_id,problem_id)
);
CREATE INDEX idx_problem_releases_problem ON problem_release_items(problem_id);
