-- 운영 작업은 일반 제출 큐와 점수 계산에서 분리합니다. 입력은 배치당 한 벌만 고정합니다.
CREATE TABLE admin_judge_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('REFERENCE','REJUDGE')),
    state TEXT NOT NULL DEFAULT 'RUNNING' CHECK (state IN ('RUNNING','READY','FAILED','APPLIED','CANCELLED')),
    problem_id BIGINT NOT NULL REFERENCES problems(id),
    contest_id BIGINT REFERENCES group_contests(id),
    creator_id BIGINT NOT NULL REFERENCES users(id),
    reason TEXT NOT NULL CHECK (length(reason) BETWEEN 1 AND 500),
    config JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_by BIGINT REFERENCES users(id), decided_at TIMESTAMPTZ, applied_impact JSONB
);
CREATE UNIQUE INDEX idx_admin_judge_active ON admin_judge_batches(problem_id,kind) WHERE state='RUNNING';
CREATE TABLE admin_judge_inputs (
    batch_id BIGINT NOT NULL REFERENCES admin_judge_batches(id),
    kind TEXT NOT NULL CHECK (kind IN ('EXAMPLE','HIDDEN')), display_order INTEGER NOT NULL,
    case_id BIGINT, input_data TEXT NOT NULL, expected_output TEXT NOT NULL, compare_type TEXT,
    PRIMARY KEY (batch_id, kind, display_order)
);
-- 기존 제출 원문은 submissions에 이미 보관합니다. 수정 가능한 참고 정답 코드만 별도 고정합니다.
CREATE TABLE admin_judge_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES admin_judge_batches(id), submission_id BIGINT REFERENCES submissions(id),
    language TEXT NOT NULL, reference_code TEXT, old_result JSONB,
    CHECK ((submission_id IS NULL) = (reference_code IS NOT NULL)),
    state TEXT NOT NULL DEFAULT 'QUEUED' CHECK (state IN ('QUEUED','RUNNING','DONE')),
    attempts INTEGER NOT NULL DEFAULT 0, token UUID, lease_until TIMESTAMPTZ,
    verdict TEXT, elapsed_ms INTEGER, results JSONB, diagnostic JSONB, image_id TEXT,
    UNIQUE (batch_id, submission_id)
);
CREATE INDEX idx_admin_judge_jobs_queue ON admin_judge_jobs (state, id);
CREATE INDEX idx_admin_judge_jobs_batch ON admin_judge_jobs (batch_id, id);
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='cobweb_judge_runtime') THEN
        GRANT SELECT ON admin_judge_batches, admin_judge_inputs, admin_judge_jobs TO cobweb_judge_runtime;
        GRANT UPDATE (state) ON admin_judge_batches TO cobweb_judge_runtime;
        GRANT UPDATE (state, attempts, token, lease_until, verdict, elapsed_ms, results, diagnostic, image_id)
            ON admin_judge_jobs TO cobweb_judge_runtime;
    END IF;
END $$;
